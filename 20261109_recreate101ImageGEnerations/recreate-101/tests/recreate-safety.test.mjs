import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

const script=fileURLToPath(new URL('../scripts/recreate.mjs',import.meta.url));
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
function fixture(){const dir=fs.mkdtempSync(path.join(os.tmpdir(),'recreate-safety-'));const input=path.join(dir,'input.png');assert.equal(spawnSync('convert',['-size','30x20','xc:blue',input]).status,0);return {dir,input};}
function run(args,env=process.env){return spawnSync(process.execPath,[script,...args],{encoding:'utf8',env});}
function runDir(dir){return path.join(dir,fs.readdirSync(dir).find(x=>x.includes('.recreate-101.')));}

test('invalid generated bytes never become a committed frame',()=>{
 const {dir,input}=fixture(),bin=path.join(dir,'bin');fs.mkdirSync(bin);const real=spawnSync('which',['convert'],{encoding:'utf8'}).stdout.trim();
 const wrapper=path.join(bin,'convert');fs.writeFileSync(wrapper,`#!/usr/bin/env node\nconst {spawnSync}=require('node:child_process');\nif(process.argv.at(-1)==='png:-'){process.stdout.write('not png');process.exit(0);}\nconst r=spawnSync(${JSON.stringify(real)},process.argv.slice(2),{encoding:'buffer'});if(r.stdout)process.stdout.write(r.stdout);if(r.stderr)process.stderr.write(r.stderr);process.exit(r.status??1);\n`);fs.chmodSync(wrapper,0o755);
 const env={...process.env,PATH:`${bin}:${process.env.PATH}`};const r=run(['run','--input',input,'--provider','mock','--iterations','1','--budget-usd','0'],env);assert.equal(r.status,0,r.stderr);
 const d=runDir(dir),m=JSON.parse(fs.readFileSync(path.join(d,'manifest.json')));assert.equal(m.completed,0);assert.equal(m.status,'unresolved request');assert.equal(fs.existsSync(path.join(d,'frames/0001.png')),false);assert.equal(fs.readdirSync(path.join(d,'frames')).some(x=>x.includes('.tmp.png')),false);
});

test('GIF frames use a shared 768 square canvas',()=>{
 const {dir,input}=fixture();const r=run(['run','--input',input,'--provider','mock','--iterations','1','--budget-usd','0']);assert.equal(r.status,0,r.stderr);const d=runDir(dir),m=JSON.parse(fs.readFileSync(path.join(d,'manifest.json'))),frame=path.join(d,'frames/0001.png');
 assert.equal(spawnSync('convert',['-size','10x30','xc:red',frame]).status,0);m.frames[1].sha256=sha(frame);fs.writeFileSync(path.join(d,'manifest.json'),JSON.stringify(m));
 const encoded=run(['encode','--run-dir',d]);assert.equal(encoded.status,0,encoded.stderr);
 const geometry=spawnSync('identify',['-format','%wx%h\n',path.join(d,'evolution.gif')],{encoding:'utf8'});assert.equal(geometry.status,0,geometry.stderr);assert.deepEqual(geometry.stdout.trim().split('\n'),['768x768','768x768']);
});
