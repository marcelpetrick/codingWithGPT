# Output: tests/fixtures/screenshots/<name>.png and tests/fixtures/screenshots/index.yaml
#         (which message fixture, theme, zoom and device pixel ratio each image uses).
# Note:   Images come from the Capture Test Window, never from LinkedIn.
#         Re-run after layout changes.
# Exit:   0 written; 1 rendering failed.
import os
import sys
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

import yaml  # noqa: E402
from PySide6.QtWidgets import QApplication  # noqa: E402

from linkedin_reply_assistant.model import load_conversation  # noqa: E402
from linkedin_reply_assistant.testwindow import render  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
MESSAGES = ROOT / "tests" / "fixtures" / "messages"
OUT = ROOT / "tests" / "fixtures" / "screenshots"
# name: (message fixture, theme, zoom, device pixel ratio) - covers VISION §23.3
CASES = {
    "light_normal_short": ("friendly_connection_01", "light", 1.0, 1.0),
    "dark_normal": ("sales_pitch_01", "dark", 1.0, 1.0),
    "light_zoom_multiline": ("substantive_01", "light", 1.25, 1.0),
    "light_hidpi_german": ("recruiting_de_01", "light", 1.0, 2.0),
    "dark_small_short": ("congratulations_01", "dark", 0.9, 1.0),
}


def main() -> int:
    app = QApplication.instance() or QApplication(sys.argv)
    OUT.mkdir(parents=True, exist_ok=True)
    index = {}
    for name, (fixture, theme, zoom, dpr) in CASES.items():
        conversation = load_conversation(MESSAGES / f"{fixture}.yaml")
        render(conversation, OUT / f"{name}.png", theme, zoom, dpr)
        index[name] = {"messages": fixture, "theme": theme, "zoom": zoom, "dpr": dpr}
        print(f"wrote {name}.png")
    (OUT / "index.yaml").write_text(
        "# Generated by scripts/make_ocr_fixtures.py. Synthetic content only.\n"
        + yaml.safe_dump(index, sort_keys=True)
    )
    del app
    return 0


if __name__ == "__main__":
    sys.exit(main())
